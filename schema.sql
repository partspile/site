-- Schema for PostgreSQL database

-- Ad Category table
CREATE TABLE AdCategory (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    name TEXT NOT NULL UNIQUE CHECK (length(name) > 0)
);

-- Specification field metadata tables
CREATE TABLE SpecField (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    name TEXT NOT NULL UNIQUE CHECK (length(name) > 0),
    display_name TEXT NOT NULL,
    field_type TEXT NOT NULL CHECK (field_type IN ('string', 'int', 'float64')),
    table_name TEXT NOT NULL,
    qdrant_type TEXT NOT NULL CHECK (qdrant_type IN ('keyword', 'keyword_array', 'integer', 'float', 'geo'))
);

CREATE TABLE AdCategoryField (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    spec_field_id INTEGER NOT NULL REFERENCES SpecField(id),
    spec_table_name TEXT NOT NULL,
    spec_table_field_name TEXT NOT NULL,
    ad_spec_table_name TEXT NOT NULL,
    priority_order INTEGER NOT NULL,
    next_in_chain INTEGER NOT NULL DEFAULT 0,
    is_required INTEGER NOT NULL DEFAULT 1,
    show_in_filters INTEGER NOT NULL DEFAULT 0,
    UNIQUE (ad_category_id, spec_field_id)
);
CREATE INDEX idx_adcategoryfield_category ON AdCategoryField(ad_category_id);
CREATE INDEX idx_adcategoryfield_order ON AdCategoryField(ad_category_id, priority_order);

-- Specification field tables
CREATE TABLE Make (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE Year (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE Model (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE Engine (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE Breed (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE PartCategory (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

CREATE TABLE PartSubCategory (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    value TEXT NOT NULL CHECK (length(value) > 0)
);

-- Specification chain tables
-- SpecVehicle: for 4-field vehicle chains (make->year->model->engine)
CREATE TABLE SpecVehicle (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    make_id INTEGER NOT NULL REFERENCES Make(id),
    year_id INTEGER NOT NULL REFERENCES Year(id),
    model_id INTEGER NOT NULL REFERENCES Model(id),
    engine_id INTEGER NOT NULL REFERENCES Engine(id),
    UNIQUE (ad_category_id, make_id, year_id, model_id, engine_id)
);
CREATE INDEX idx_specvehicle_category ON SpecVehicle(ad_category_id);
CREATE INDEX idx_specvehicle_make ON SpecVehicle(make_id);
CREATE INDEX idx_specvehicle_year ON SpecVehicle(year_id);
CREATE INDEX idx_specvehicle_model ON SpecVehicle(model_id);
CREATE INDEX idx_specvehicle_engine ON SpecVehicle(engine_id);

-- SpecAgricultural: for 3-field vehicle chains (make->year->model)
CREATE TABLE SpecAgricultural (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    make_id INTEGER NOT NULL REFERENCES Make(id),
    year_id INTEGER NOT NULL REFERENCES Year(id),
    model_id INTEGER NOT NULL REFERENCES Model(id),
    UNIQUE (ad_category_id, make_id, year_id, model_id)
);
CREATE INDEX idx_specagricultural_category ON SpecAgricultural(ad_category_id);
CREATE INDEX idx_specagricultural_make ON SpecAgricultural(make_id);
CREATE INDEX idx_specagricultural_year ON SpecAgricultural(year_id);
CREATE INDEX idx_specagricultural_model ON SpecAgricultural(model_id);

-- SpecBicycle: for 2-field vehicle chains (make->model)
CREATE TABLE SpecBicycle (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    make_id INTEGER NOT NULL REFERENCES Make(id),
    model_id INTEGER NOT NULL REFERENCES Model(id),
    UNIQUE (ad_category_id, make_id, model_id)
);
CREATE INDEX idx_specbicycle_category ON SpecBicycle(ad_category_id);
CREATE INDEX idx_specbicycle_make ON SpecBicycle(make_id);
CREATE INDEX idx_specbicycle_model ON SpecBicycle(model_id);

-- SpecPart: for part chains (part_category->part_subcategory)
CREATE TABLE SpecPart (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    part_category_id INTEGER NOT NULL REFERENCES PartCategory(id),
    part_subcategory_id INTEGER NOT NULL REFERENCES PartSubCategory(id),
    UNIQUE (ad_category_id, part_category_id, part_subcategory_id)
);
CREATE INDEX idx_specpart_category ON SpecPart(ad_category_id);
CREATE INDEX idx_specpart_part_category ON SpecPart(part_category_id);
CREATE INDEX idx_specpart_part_subcategory ON SpecPart(part_subcategory_id);

-- Location table
CREATE TABLE Location (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    raw_text TEXT UNIQUE NOT NULL CHECK (length(raw_text) > 0),
    city TEXT NOT NULL,
    admin_area TEXT NOT NULL,
    country TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_location_raw_text ON Location(raw_text);

-- Phone verification table
CREATE TABLE PhoneVerification (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    phone TEXT NOT NULL,
    verification_code TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    registration_name TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_phoneverification_phone ON PhoneVerification(phone);
CREATE INDEX idx_phoneverification_created_at ON PhoneVerification(created_at);

-- User tables
CREATE TABLE Users (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    encrypted_name BYTEA NOT NULL,
    name_nonce BYTEA NOT NULL,
    name_hash TEXT NOT NULL UNIQUE,
    encrypted_phone BYTEA NOT NULL,
    phone_nonce BYTEA NOT NULL,
    phone_hash TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    password_algo TEXT NOT NULL DEFAULT 'argon2id',
    phone_verified INTEGER NOT NULL DEFAULT 0,
    verification_code TEXT NOT NULL DEFAULT '',
    notification_method TEXT NOT NULL DEFAULT 'sms',
    encrypted_email_address BYTEA,
    email_address_nonce BYTEA,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_admin INTEGER NOT NULL DEFAULT 0,
    sms_opted_out INTEGER NOT NULL DEFAULT 0,
    summary_notifications_enabled INTEGER DEFAULT 0,
    summary_notifications_frequency TEXT DEFAULT 'daily',
    deleted_at TIMESTAMP
);
CREATE INDEX idx_user_deleted_at ON Users(deleted_at);
CREATE INDEX idx_user_name_hash ON Users(name_hash);
CREATE INDEX idx_user_phone_hash ON Users(phone_hash);

-- Ad tables
CREATE TABLE Ad (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_category_id INTEGER NOT NULL REFERENCES AdCategory(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,
    user_id INTEGER NOT NULL REFERENCES Users(id),
    image_count INTEGER DEFAULT 0,
    location_id INTEGER REFERENCES Location(id),
    click_count INTEGER DEFAULT 0,
    last_clicked_at TIMESTAMP,
    has_vector INTEGER DEFAULT 0
);
CREATE INDEX idx_ad_created_at_id ON Ad(created_at, id);
CREATE INDEX idx_ad_deleted_at ON Ad(deleted_at);
CREATE INDEX idx_ad_ad_category_id ON Ad(ad_category_id);

-- AdSpecification tables - one per spec table type
CREATE TABLE AdSpecVehicle (
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    spec_id INTEGER NOT NULL REFERENCES SpecVehicle(id),
    PRIMARY KEY (ad_id, spec_id)
);
CREATE INDEX idx_adspecvehicle_ad_id ON AdSpecVehicle(ad_id);
CREATE INDEX idx_adspecvehicle_spec_id ON AdSpecVehicle(spec_id);

CREATE TABLE AdSpecAgricultural (
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    spec_id INTEGER NOT NULL REFERENCES SpecAgricultural(id),
    PRIMARY KEY (ad_id, spec_id)
);
CREATE INDEX idx_adspecagricultural_ad_id ON AdSpecAgricultural(ad_id);
CREATE INDEX idx_adspecagricultural_spec_id ON AdSpecAgricultural(spec_id);

CREATE TABLE AdSpecBicycle (
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    spec_id INTEGER NOT NULL REFERENCES SpecBicycle(id),
    PRIMARY KEY (ad_id, spec_id)
);
CREATE INDEX idx_adspecbicycle_ad_id ON AdSpecBicycle(ad_id);
CREATE INDEX idx_adspecbicycle_spec_id ON AdSpecBicycle(spec_id);

CREATE TABLE AdSpecPart (
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    spec_id INTEGER NOT NULL REFERENCES SpecPart(id),
    PRIMARY KEY (ad_id, spec_id)
);
CREATE INDEX idx_adspecpart_ad_id ON AdSpecPart(ad_id);
CREATE INDEX idx_adspecpart_spec_id ON AdSpecPart(spec_id);

CREATE TABLE BookmarkedAd (
    user_id INTEGER NOT NULL REFERENCES Users(id),
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    bookmarked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, ad_id)
);
CREATE INDEX idx_bookmarkedad_user_id ON BookmarkedAd(user_id);
CREATE INDEX idx_bookmarkedad_ad_id ON BookmarkedAd(ad_id);

CREATE TABLE UserAdClick (
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    user_id INTEGER NOT NULL REFERENCES Users(id),
    click_count INTEGER DEFAULT 0,
    last_clicked_at TIMESTAMP,
    PRIMARY KEY (ad_id, user_id)
);


-- Messaging system tables
CREATE TABLE Conversation (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    user1_id INTEGER NOT NULL REFERENCES Users(id),
    user2_id INTEGER NOT NULL REFERENCES Users(id),
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    user1_read BOOLEAN DEFAULT FALSE,
    user2_read BOOLEAN DEFAULT FALSE,
    user1_first_msg_notified INTEGER DEFAULT 0,
    user2_first_msg_notified INTEGER DEFAULT 0,
    pinged_by_user_id INTEGER REFERENCES Users(id),
    pinged_at TIMESTAMP,
    UNIQUE (user1_id, user2_id, ad_id)
);
CREATE INDEX idx_conversation_user1_id ON Conversation(user1_id);
CREATE INDEX idx_conversation_user2_id ON Conversation(user2_id);
CREATE INDEX idx_conversation_ad_id ON Conversation(ad_id);
CREATE INDEX idx_conversation_updated_at ON Conversation(updated_at);

CREATE TABLE Message (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    conversation_id INTEGER NOT NULL REFERENCES Conversation(id),
    sender_id INTEGER NOT NULL REFERENCES Users(id),
    encrypted_content BYTEA NOT NULL,
    nonce BYTEA NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);
CREATE INDEX idx_message_conversation_id ON Message(conversation_id);
CREATE INDEX idx_message_sender_id ON Message(sender_id);
CREATE INDEX idx_message_created_at ON Message(created_at);
CREATE INDEX idx_message_read_at ON Message(read_at);

-- Rock system tables
CREATE TABLE UserRock (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    user_id INTEGER NOT NULL REFERENCES Users(id),
    rock_count INTEGER NOT NULL DEFAULT 3,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id)
);
CREATE INDEX idx_userrock_user_id ON UserRock(user_id);

CREATE TABLE AdRock (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ad_id INTEGER NOT NULL REFERENCES Ad(id),
    thrower_id INTEGER NOT NULL REFERENCES Users(id),
    conversation_id INTEGER NOT NULL REFERENCES Conversation(id),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    resolved_by INTEGER REFERENCES Users(id)
);
CREATE INDEX idx_adrock_ad_id ON AdRock(ad_id);
CREATE INDEX idx_adrock_thrower_id ON AdRock(thrower_id);
CREATE INDEX idx_adrock_conversation_id ON AdRock(conversation_id);
CREATE INDEX idx_adrock_resolved_at ON AdRock(resolved_at);